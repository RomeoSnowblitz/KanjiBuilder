# Packs kanji\Radicals.txt, kanji\Hanzi.txt, kanji\Kanji.txt and kanji\LearnOrder.txt into kanji-data.js
# (window.KANJI_DATA = { radicals: [...], hanzi: [...], kanji: [...], learn: [...] }), one TSV row per string,
# header rows dropped. The page is opened from file://, so the data has to ship as a script.
# ASCII-only on purpose: Windows PowerShell 5.1 reads BOM-less scripts as ANSI.
param(
    [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path,
    [string]$Out = ''
)

$ErrorActionPreference = 'Stop'
if (-not $Out) { $Out = Join-Path $Root 'kanji-data.js' }
$utf8 = New-Object System.Text.UTF8Encoding($false)

function ConvertTo-JsString([string]$s) {
    $sb = New-Object System.Text.StringBuilder ($s.Length + 8)
    [void]$sb.Append('"')
    foreach ($ch in $s.ToCharArray()) {
        $code = [int]$ch
        switch ($code) {
            0x22 { [void]$sb.Append('\"'); continue }
            0x5C { [void]$sb.Append('\\'); continue }
            0x09 { [void]$sb.Append('\t'); continue }
            0x0A { [void]$sb.Append('\n'); continue }
            0x0D { [void]$sb.Append('\r'); continue }
            0x2028 { [void]$sb.Append('\u2028'); continue }
            0x2029 { [void]$sb.Append('\u2029'); continue }
            default {
                if ($code -lt 0x20) { [void]$sb.Append(('\u{0:x4}' -f $code)) }
                else { [void]$sb.Append($ch) }
            }
        }
    }
    [void]$sb.Append('"')
    return $sb.ToString()
}

function Get-Rows([string]$path) {
    if (-not (Test-Path -LiteralPath $path)) {
        Write-Warning "missing $path (writing an empty list)"
        return @()
    }
    $lines = [IO.File]::ReadAllLines($path, $utf8)
    return @($lines | Select-Object -Skip 1 | Where-Object { $_.Trim() -ne '' })
}

$sets = [ordered]@{
    radicals = Join-Path $Root 'kanji\Radicals.txt'
    hanzi    = Join-Path $Root 'kanji\Hanzi.txt'
    kanji    = Join-Path $Root 'kanji\Kanji.txt'
    learn    = Join-Path $Root 'kanji\LearnOrder.txt'
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* Generated by kanji/tools/kb_build_js.ps1 from kanji/Radicals.txt, kanji/Hanzi.txt, kanji/Kanji.txt and kanji/LearnOrder.txt. Do not edit by hand. */')
[void]$sb.AppendLine('window.KANJI_DATA = {')
$names = @($sets.Keys)
for ($i = 0; $i -lt $names.Count; $i++) {
    $name = $names[$i]
    $rows = Get-Rows $sets[$name]
    [void]$sb.AppendLine("  ${name}: [")
    for ($j = 0; $j -lt $rows.Count; $j++) {
        $sep = if ($j -lt $rows.Count - 1) { ',' } else { '' }
        [void]$sb.AppendLine('    ' + (ConvertTo-JsString $rows[$j]) + $sep)
    }
    $close = if ($i -lt $names.Count - 1) { '  ],' } else { '  ]' }
    [void]$sb.AppendLine($close)
    Write-Host ("{0}: {1}" -f $name, $rows.Count)
}
[void]$sb.AppendLine('};')

[IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Host ("wrote {0} ({1:N0} bytes)" -f $Out, (Get-Item -LiteralPath $Out).Length)
